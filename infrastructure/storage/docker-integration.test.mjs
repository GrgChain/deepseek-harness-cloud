import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn, execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { randomUUID } from 'node:crypto';
const exec = promisify(execFile);
const docker = async (...args) => (await exec('docker', args, { timeout: 100000, maxBuffer: 1024 * 1024 })).stdout.trim();
const capacityGiB = Number(process.env.HC_STORAGE_TEST_GIB ?? 10);
assert.ok(Number.isInteger(capacityGiB) && capacityGiB >= 1 && capacityGiB <= 100);
test(`independent real ${capacityGiB} GiB filesystem enforces capacity and survives compute deletion`, { skip: !process.env.HC_STORAGE_IMAGE || !process.env.HC_RUNTIME_IMAGE, timeout: 240000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), 'hc-storage-contract-'));
  const config = { schema_version: 1, asset_id: randomUUID(), instance_id: randomUUID(), org_id: randomUUID(), owner_id: randomUUID(), capacity_bytes: capacityGiB * 2 ** 30 };
  const volume = 'hc-' + config.asset_id, name = 'hc-storage-test-' + config.asset_id;
  let device;
  const helper = action => new Promise((resolve, reject) => {
    const child = spawn('docker', ['run', '--rm', '-i', '--network', 'none', '--privileged', '--read-only', '--tmpfs', '/mnt:rw,nosuid,nodev,size=1m', '--mount', `type=bind,src=${root},dst=/assets`, '--mount', 'type=bind,src=/dev,dst=/host-dev', process.env.HC_STORAGE_IMAGE, action], { stdio: ['pipe', 'pipe', 'pipe'] });
    let out = ''; child.stdout.on('data', b => { out += b; }); child.stderr.resume(); child.on('error', reject); child.on('exit', code => code === 0 ? resolve(JSON.parse(out)) : reject(new Error('Trusted storage helper rejected operation'))); child.stdin.end(JSON.stringify(config));
  });
  t.after(async () => {
    await docker('rm', '-f', name + '-held').catch(() => {});
    await docker('rm', '-f', name).catch(() => {});
    await docker('volume', 'rm', volume).catch(() => {});
    {
      // These paths are generated by this fixture, and the volume/container have
      // already been removed. No unrelated device or data is reclaimed.
      await docker('run', '--rm', '--network', 'none', '--privileged', '--env', 'ASSET=' + config.asset_id, '--mount', 'type=bind,src=/dev,dst=/host-dev', '--mount', `type=bind,src=${root},dst=/assets`, '--entrypoint', 'python3', process.env.HC_STORAGE_IMAGE, '-c', "import os,subprocess,shutil; p='/host-dev/hc-cloud/'+os.environ['ASSET']\nif os.path.islink(p):\n d=os.readlink(p); subprocess.run(['losetup','-d',d],check=True); os.unlink(p)\na='/assets/'+os.environ['ASSET']\nif os.path.isdir(a): shutil.rmtree(a)");
    }
    await rm(root, { recursive: true, force: true });
  });
  const prepared = await helper('prepare'); device = prepared.device;
  assert.equal(prepared.capacity_bytes, config.capacity_bytes); assert.equal(prepared.filesystem_id, config.asset_id);
  await assert.rejects(helper('prepare'), /rejected/);
  await docker('volume', 'create', '--driver', 'local', '--opt', 'type=ext4', '--opt', 'o=nosuid,nodev', '--opt', 'device=' + device, '--label', 'hc.asset_id=' + config.asset_id, '--label', 'hc.instance_id=' + config.instance_id, '--label', 'hc.owner_id=' + config.owner_id, '--label', 'hc.org_id=' + config.org_id, volume);
  await docker('create', '--name', name + '-held', '--network', 'none', '--mount', `type=volume,src=${volume},dst=/data,volume-nocopy`, '--entrypoint', 'node', process.env.HC_RUNTIME_IMAGE, '-e', 'setInterval(()=>{},10000)');
  assert.deepEqual(await helper('inspect'), prepared);
  await docker('rm', name + '-held');
  const run = script => docker('run', '--rm', '--name', name, '--network', 'none', '--read-only', '--cap-drop', 'ALL', '--security-opt', 'no-new-privileges', '--user', '1000:1000', '--mount', `type=volume,src=${volume},dst=/data,volume-nocopy`, '--entrypoint', 'python3', process.env.HC_RUNTIME_IMAGE, '-c', script);
  const written = await run(`import os,errno,json; p='/data/retained-proof'; open(p,'w').write('original-data'); f=os.statvfs('/data'); print(json.dumps({'bytes':f.f_blocks*f.f_frsize})); fd=os.open('/data/too-big',os.O_CREAT|os.O_RDWR,0o600)\ntry:\n os.posix_fallocate(fd,0,${capacityGiB+1}*2**30); raise RuntimeError('capacity was not enforced')\nexcept OSError as e:\n assert e.errno==errno.ENOSPC\nfinally:\n os.close(fd); os.unlink('/data/too-big')`);
  assert.ok(JSON.parse(written).bytes <= capacityGiB * 2 ** 30);
  assert.equal(await run("print(open('/data/retained-proof').read())"), 'original-data');
  assert.deepEqual(await helper('inspect'), prepared);
  await docker('volume', 'rm', volume);
  assert.deepEqual(await helper('inspect'), prepared);
});
