var (
	ErrSuperseded       = errors.New("instance execution intent was superseded")
	ErrExecutionRevoked = errors.New("instance execution authority or credential was revoked")
	ErrInvalidEvidence  = errors.New("runtime completion evidence is missing or invalid")
)
var uuidPattern = regexp.MustCompile(`^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$`)
var hostPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9.-]{0,252}$`)

type Intent struct {
	SchemaVersion      int             `json:"schema_version"`
	ExpectedVersion    int64           `json:"expected_instance_version"`
	Desired            string          `json:"target_desired_state"`
	Reason             string          `json:"reason"`
	RequestID          string          `json:"request_id"`
	AcceptedGeneration *int64          `json:"accepted_auth_generation,omitempty"`
	Target             json.RawMessage `json:"target_snapshot,omitempty"`
	ConfirmedName      *string         `json:"confirmed_name,omitempty"`
	External           *BuildAttempt   `json:"external_build,omitempty"`
}

func parseIntent(data []byte, action, actorKind string) (Intent, error) {
	var v Intent
	if webapi.StrictUnmarshal(data, &v) != nil || v.SchemaVersion != 1 || v.ExpectedVersion < 1 || v.RequestID == "" || len(v.RequestID) > 128 {
		return v, ErrInvalidEvidence
	}
	if actorKind == "USER" {
		if v.Reason != "USER_REQUEST" || v.AcceptedGeneration == nil || *v.AcceptedGeneration < 1 {
			return v, ErrInvalidEvidence
		}
	} else if actorKind != "SYSTEM" || action != "STOP" || (v.Reason != "AUTH_REVOKED" && v.Reason != "CREDENTIAL_REVOKED") || v.AcceptedGeneration != nil {
		return v, ErrInvalidEvidence
	}
	switch action {
	case "CREATE", "START":
		if v.Desired != "RUNNING" || len(v.Target) == 0 || v.ConfirmedName != nil {
			return v, ErrInvalidEvidence
		}
	case "CONFIGURE":
		if (v.Desired != "RUNNING" && v.Desired != "STOPPED") || len(v.Target) == 0 || v.ConfirmedName != nil {
			return v, ErrInvalidEvidence
		}
	case "STOP":
		if v.Desired != "STOPPED" || len(v.Target) > 0 || v.ConfirmedName != nil {
			return v, ErrInvalidEvidence
		}
	case "DELETE":
		if v.Desired != "DELETED" || len(v.Target) > 0 || v.ConfirmedName == nil {
			return v, ErrInvalidEvidence
		}
	default:
		return v, ErrInvalidEvidence
	}
	if v.External != nil && !v.External.valid(action, v.Desired) {
		return v, ErrInvalidEvidence
	}
	if len(v.Target) > 0 {
		if _, err := instances.DecodeSnapshot(v.Target); err != nil {
			return v, ErrInvalidEvidence
		}
	}
	return v, nil
}

// RuntimeEvidence is generated by the trusted adapter after original-asset,
// container, native authentication and readiness checks. It never crosses API JSON.
type RuntimeEvidence struct {
	WorkspaceID, BuildID, Host, IP, Generation string
	NativeCookie                               []byte
	NativeExpiresAt, CheckedAt                 time.Time
}
type Completion struct {
	ComputeAbsent, AssetReady, WorkspaceAbsent bool
	FilesystemID                               string
	Running                                    *RuntimeEvidence
}
type ExecutionStore struct {
	pool        *pgxpool.Pool
	cipher      *security.SecretCipher
	environment string
}

func NewExecutionStore(pool *pgxpool.Pool, cipher *security.SecretCipher, environment string) *ExecutionStore {
	return &ExecutionStore{pool, cipher, environment}
}

type executionRecord struct {
	Org, Owner, Name, Action, ActorKind, Trace, Desired string
	ActorID                                             *string
	Snapshot                                            instances.Snapshot
	Encoded                                             []byte
	Intent                                              Intent
	Version                                             int64
	AssetID, WorkspaceID                                *string
	AssetStatus                                         string
	AssetCapacity                                       int64
	Authorized                                          bool
}

// lockExecution observes immutable ownership first, then takes the documented
// membership -> model head -> quota -> instance -> operation -> outbox locks.
// No network work or credential material is involved in these transactions.
func (s *ExecutionStore) lockExecution(ctx context.Context, tx pgx.Tx, lease Lease, allowSuperseded bool) (executionRecord, error) {
	var r executionRecord
	if !uuidPattern.MatchString(lease.ID) || !uuidPattern.MatchString(lease.InstanceID) || !workerName.MatchString(lease.Owner) || lease.Token < 1 {
		return r, ErrLostLease
	}
	err := tx.QueryRow(ctx, `SELECT i.org_id::text,i.owner_id::text FROM instances i JOIN operations o ON o.instance_id=i.id WHERE o.id=$1 AND i.id=$2`, lease.ID, lease.InstanceID).Scan(&r.Org, &r.Owner)
	if errors.Is(err, pgx.ErrNoRows) {
		return r, ErrLostLease
	}
	if err != nil {
		return r, err
	}
	err = tx.QueryRow(ctx, `SELECT public.hc_worker_lock_authority($1,$2)`, r.Org, r.Owner).Scan(&r.Authorized)
	if err != nil {
		return r, err
	}
	var ignored string
	if err = tx.QueryRow(ctx, `SELECT org_id::text FROM quota_policies WHERE org_id=$1 FOR UPDATE`, r.Org).Scan(&ignored); err != nil {
		return r, err
	}
	err = tx.QueryRow(ctx, `SELECT name,version,desired_state,config_snapshot,storage_asset_id::text,workspace_id::text FROM instances WHERE id=$1 AND org_id=$2 AND owner_id=$3 FOR UPDATE`, lease.InstanceID, r.Org, r.Owner).Scan(&r.Name, &r.Version, &r.Desired, &r.Encoded, &r.AssetID, &r.WorkspaceID)
	if err != nil {
		return r, err
	}
	var raw []byte
	err = tx.QueryRow(ctx, `SELECT type,actor_kind,actor_id::text,intent,trace_id FROM operations WHERE id=$1 AND instance_id=$2 AND lease_owner=$3 AND lease_token=$4 AND lease_expires_at>clock_timestamp() AND status IN ('RUNNING','UNCERTAIN') FOR UPDATE`, lease.ID, lease.InstanceID, lease.Owner, lease.Token).Scan(&r.Action, &r.ActorKind, &r.ActorID, &raw, &r.Trace)
	if errors.Is(err, pgx.ErrNoRows) {
		return r, ErrLostLease
	}
	if err != nil {
		return r, err
	}
	if r.Intent, err = parseIntent(raw, r.Action, r.ActorKind); err != nil {
		return r, err
	}
	if r.Authorized && r.ActorKind == "USER" && (r.Action == "CREATE" || r.Action == "START" || r.Action == "CONFIGURE") {
		err = tx.QueryRow(ctx, `SELECT public.hc_has_permission($1,$2,$3) AND ($4<>'RUNNING' OR public.hc_has_permission($1,$2,'instances:start'))`, r.Org, r.Owner, "instances:"+strings.ToLower(r.Action), r.Intent.Desired).Scan(&r.Authorized)
		if err != nil {
			return r, err
		}
	}
	// A SYSTEM STOP releases only compute. It must preserve an already accepted
	// DELETE target so security cleanup cannot silently undo the user's intent.
	desiredMatches := r.Desired == r.Intent.Desired || (r.ActorKind == "SYSTEM" && r.Action == "STOP" && r.Intent.Desired == "STOPPED" && r.Desired == "DELETED")
	if r.Version == math.MaxInt64 || r.Version < r.Intent.ExpectedVersion || (!allowSuperseded && (r.Version != r.Intent.ExpectedVersion || !desiredMatches)) {
		return r, ErrSuperseded
	}
	if r.Snapshot, err = instances.DecodeSnapshot(r.Encoded); err != nil {
		return r, err
	}
	if len(r.Intent.Target) > 0 {
		target, err := instances.DecodeSnapshot(r.Intent.Target)
		if err != nil {
			return r, err
		}
		if err = s.validateTarget(ctx, tx, r.Action, r.Snapshot, target); err != nil {
			return r, err
		}
	}
	expectedTemplate := r.Snapshot.TemplateVersion
	if len(r.Intent.Target) > 0 {
		target, _ := instances.DecodeSnapshot(r.Intent.Target)
		expectedTemplate = target.TemplateVersion
	}
	if r.Intent.External != nil && r.Intent.External.TemplateVersion != expectedTemplate {
		return r, ErrInvalidEvidence
	}
	if r.Action == "DELETE" && *r.Intent.ConfirmedName != r.Name {
		return r, ErrInvalidEvidence
	}
	if r.AssetID != nil {
		err = tx.QueryRow(ctx, `SELECT status,capacity_bytes FROM storage_assets WHERE id=$1 AND instance_id=$2 AND org_id=$3 AND owner_id=$4`, *r.AssetID, lease.InstanceID, r.Org, r.Owner).Scan(&r.AssetStatus, &r.AssetCapacity)
		if err != nil {
			return r, err
		}
	}
	err = tx.QueryRow(ctx, `SELECT id::text FROM outbox_events WHERE operation_id=$1 AND status='PENDING' FOR UPDATE`, lease.ID).Scan(&ignored)
	if errors.Is(err, pgx.ErrNoRows) {
		return r, ErrLostLease
	}
	return r, err
}
func (s *ExecutionStore) Complete(ctx context.Context, lease Lease, result Completion) error {
	if (result.Running == nil) == !result.ComputeAbsent || (result.Running != nil && result.WorkspaceAbsent) {
		return ErrInvalidEvidence
	}
	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback(context.Background())
	r, err := s.lockExecution(ctx, tx, lease, false)
	if err != nil {
		return err
	}
	var now time.Time
	if err = tx.QueryRow(ctx, `SELECT clock_timestamp()`).Scan(&now); err != nil {
		return err
	}
	target := r.Snapshot
	encoded := r.Encoded
	if len(r.Intent.Target) > 0 {
		target, err = instances.DecodeSnapshot(r.Intent.Target)
		if err != nil {
			return err
		}
		encoded = r.Intent.Target
	}
	if err = s.validateTarget(ctx, tx, r.Action, r.Snapshot, target); err != nil {
		return err
	}
	if r.Action == "DELETE" && !result.WorkspaceAbsent {
		return ErrInvalidEvidence
	}
	running := r.Intent.Desired == "RUNNING"
	if running != (result.Running != nil) {
		return ErrInvalidEvidence
	}
	if result.AssetReady && (!uuidPattern.MatchString(result.FilesystemID) || r.AssetID == nil || r.AssetCapacity != target.Spec.Storage || r.AssetStatus == "DELETED" || r.AssetStatus == "RECLAIM_PENDING" || r.AssetStatus == "RESTORING") {
		return ErrInvalidEvidence
	}
	if running && !result.AssetReady {
		return ErrInvalidEvidence
	}
	var modelChecked, modelExpires time.Time
	if running || r.Action == "CONFIGURE" {
		if !r.Authorized || r.ActorKind != "USER" || r.ActorID == nil || *r.ActorID != r.Owner {
			return ErrExecutionRevoked
		}
		var valid bool
		err = tx.QueryRow(ctx, `SELECT c.status='VALID' AND c.revoked_at IS NULL AND sec.revoked_at IS NULL AND c.provider=$4 AND c.protocol=$5 AND c.model=$6 AND public.hc_model_available(c.org_id,$7,c.id,c.version),v.checked_at,v.expires_at FROM model_configurations c JOIN secrets sec ON sec.id=c.credential_ref AND sec.org_id=c.org_id JOIN model_validations v ON v.config_id=c.id AND v.config_version=c.version WHERE c.org_id=$1 AND c.id=$2 AND c.version=$3 AND v.status='HEALTHY' AND v.checked_at<=clock_timestamp() AND v.expires_at>clock_timestamp()`, r.Org, target.ModelID, target.ModelVersion, target.Provider, target.Protocol, target.Model, r.Owner).Scan(&valid, &modelChecked, &modelExpires)
		if errors.Is(err, pgx.ErrNoRows) || err == nil && !valid {
			return ErrExecutionRevoked
		}
		if err != nil {
			return err
		}
	}
	if running {
		proof := result.Running
		ip := net.ParseIP(proof.IP)
		prefix := "i-" + strings.ReplaceAll(lease.InstanceID, "-", "") + "."
		if s.cipher == nil || !uuidPattern.MatchString(proof.WorkspaceID) || !uuidPattern.MatchString(proof.BuildID) || !uuidPattern.MatchString(proof.Generation) || proof.Generation != lease.ID || !hostPattern.MatchString(proof.Host) || !strings.HasPrefix(proof.Host, prefix) || strings.Contains(proof.Host, "..") || ip == nil || ip.To4() == nil || !ip.IsPrivate() || proof.CheckedAt.After(now) || !proof.CheckedAt.Add(60*time.Second).After(now) || !proof.NativeExpiresAt.After(now) || proof.NativeExpiresAt.After(now.Add(24*time.Hour)) || len(proof.NativeCookie) == 0 || len(proof.NativeCookie) > 8192 || strings.ContainsAny(string(proof.NativeCookie), "\r\n\x00") {
			return ErrInvalidEvidence
		}
		if r.WorkspaceID != nil && *r.WorkspaceID != proof.WorkspaceID {
			return ErrInvalidEvidence
		}
		var cpu, memory, storage, instancesUsed, runningUsed int64
		err = tx.QueryRow(ctx, `SELECT COALESCE(sum(amount) FILTER(WHERE resource_type='CPU'),0),COALESCE(sum(amount) FILTER(WHERE resource_type='MEMORY'),0),COALESCE(sum(amount) FILTER(WHERE resource_type='STORAGE'),0),COALESCE(sum(amount) FILTER(WHERE resource_type='INSTANCE'),0),COALESCE(sum(amount) FILTER(WHERE resource_type='RUNNING'),0) FROM quota_reservations WHERE instance_id=$1 AND status IN ('HELD','USED')`, lease.InstanceID).Scan(&cpu, &memory, &storage, &instancesUsed, &runningUsed)
		if err != nil {
			return err
		}
		if cpu != target.Spec.CPU || memory != target.Spec.Memory || storage != target.Spec.Storage || instancesUsed != 1 || runningUsed != 1 {
			return ErrInvalidEvidence
		}
		envelope, err := s.cipher.Encrypt(proof.NativeCookie, security.Context{Environment: s.environment, OrganizationID: r.Org, RecordID: lease.InstanceID + ":" + proof.Generation, Purpose: "native-cookie"})
		if err != nil {
			return err
		}
		if _, err = tx.Exec(ctx, `INSERT INTO native_sessions(instance_id,runtime_generation,key_id,nonce,cookie_ciphertext,expires_at) VALUES($1,$2,$3,$4,$5,$6) ON CONFLICT(instance_id) DO UPDATE SET runtime_generation=EXCLUDED.runtime_generation,key_id=EXCLUDED.key_id,nonce=EXCLUDED.nonce,cookie_ciphertext=EXCLUDED.cookie_ciphertext,expires_at=EXCLUDED.expires_at`, lease.InstanceID, proof.Generation, envelope.KeyID, envelope.Nonce, envelope.Ciphertext, proof.NativeExpiresAt); err != nil {
			return err
		}
		if _, err = tx.Exec(ctx, `INSERT INTO access_routes(instance_id,host,upstream_ip,upstream_port,runtime_generation,enabled) VALUES($1,$2,$3,3080,$4,true) ON CONFLICT(instance_id) DO UPDATE SET host=EXCLUDED.host,upstream_ip=EXCLUDED.upstream_ip,upstream_port=3080,runtime_generation=EXCLUDED.runtime_generation,enabled=true`, lease.InstanceID, proof.Host, proof.IP, proof.Generation); err != nil {
			return err
		}
		for _, dimension := range []string{"application", "storage", "configuration", "access", "model"} {
			checked, expires := proof.CheckedAt, proof.CheckedAt.Add(60*time.Second)
			if dimension == "model" {
				checked, expires = modelChecked, modelExpires
			}
			if _, err = tx.Exec(ctx, `INSERT INTO instance_health(instance_id,dimension,status,checked_at,expires_at,reason_code) VALUES($1,$2,'HEALTHY',$3,$4,'') ON CONFLICT(instance_id,dimension) DO UPDATE SET status=EXCLUDED.status,checked_at=EXCLUDED.checked_at,expires_at=EXCLUDED.expires_at,reason_code=''`, lease.InstanceID, dimension, checked, expires); err != nil {
				return err
			}
		}
		if _, err = tx.Exec(ctx, `UPDATE instances SET workspace_id=$2 WHERE id=$1`, lease.InstanceID, proof.WorkspaceID); err != nil {
			return err
		}
		if _, err = tx.Exec(ctx, `UPDATE operations SET build_id=$2 WHERE id=$1`, lease.ID, proof.BuildID); err != nil {
			return err
		}
	} else {
		if _, err = tx.Exec(ctx, `UPDATE access_routes SET enabled=false WHERE instance_id=$1`, lease.InstanceID); err != nil {
			return err
		}
		if _, err = tx.Exec(ctx, `UPDATE access_sessions SET revoked_at=COALESCE(revoked_at,clock_timestamp()) WHERE instance_id=$1`, lease.InstanceID); err != nil {
			return err
		}
		if _, err = tx.Exec(ctx, `DELETE FROM native_sessions WHERE instance_id=$1`, lease.InstanceID); err != nil {
			return err
		}
		if _, err = tx.Exec(ctx, `UPDATE instance_health SET status='UNKNOWN',checked_at=NULL,expires_at=NULL,reason_code='COMPUTE_STOPPED' WHERE instance_id=$1`, lease.InstanceID); err != nil {
			return err
		}
	}
	if result.AssetReady {
		tag, updateErr := tx.Exec(ctx, `UPDATE storage_assets SET status='READY',init_version=GREATEST(init_version,1),filesystem_id=$2 WHERE id=$1 AND (filesystem_id IS NULL OR filesystem_id=$2)`, r.AssetID, result.FilesystemID)
		if updateErr != nil {
			return updateErr
		}
		if tag.RowsAffected() != 1 {
			return ErrInvalidEvidence
		}
	}
	if r.Action == "DELETE" && r.AssetID != nil {
		if _, err = tx.Exec(ctx, `UPDATE storage_assets SET status='RETAINED',retention_until=GREATEST(COALESCE(retention_until,$2::timestamptz+make_interval(days=>COALESCE((SELECT d.retention_days FROM organization_defaults d WHERE d.org_id=storage_assets.org_id),7))),$2::timestamptz+make_interval(days=>COALESCE((SELECT d.retention_days FROM organization_defaults d WHERE d.org_id=storage_assets.org_id),7))) WHERE id=$1 AND status NOT IN ('DELETED','RESTORING','RECLAIM_PENDING')`, *r.AssetID, now); err != nil {
			return err
		}
	}
	if _, err = tx.Exec(ctx, `UPDATE quota_reservations SET status=CASE WHEN resource_type='CONCURRENT' OR ($2 AND resource_type IN ('CPU','MEMORY','RUNNING')) OR ($3 AND resource_type='INSTANCE') THEN 'RELEASED' WHEN resource_type='STORAGE' AND NOT $4 THEN status ELSE 'USED' END,updated_at=clock_timestamp() WHERE instance_id=$1 AND status IN ('HELD','USED')`, lease.InstanceID, !running, r.Action == "DELETE", result.AssetReady); err != nil {
		return err
	}
	if _, err = tx.Exec(ctx, `UPDATE instances SET observed_state=$2,config_snapshot=$3,model_config_id=$4,model_config_version=$5,version=version+1,updated_at=clock_timestamp(),deleted_at=CASE WHEN $2='DELETED' THEN $6::timestamptz ELSE NULL END WHERE id=$1`, lease.InstanceID, r.Intent.Desired, encoded, target.ModelID, target.ModelVersion, now); err != nil {
		return err
	}
	// Recheck actual clock after every lock/write. A late return must not publish
	// any preceding state or release reservations after losing its lease.
	tag, err := tx.Exec(ctx, `UPDATE operations SET status='SUCCEEDED',stage='COMPLETE',error_code=NULL,error_message=NULL,reconciled_at=clock_timestamp(),lease_owner=NULL,lease_expires_at=NULL,updated_at=clock_timestamp() WHERE id=$1 AND lease_owner=$2 AND lease_token=$3 AND lease_expires_at>clock_timestamp() AND status IN ('RUNNING','UNCERTAIN')`, lease.ID, lease.Owner, lease.Token)
	if err != nil {
		return err
	}
	if tag.RowsAffected() != 1 {
		return ErrLostLease
	}
	if _, err = tx.Exec(ctx, `INSERT INTO audit_events(id,org_id,actor_id,owner_id,resource_id,action,outcome,trace_id,details) VALUES($1,$2,$3,$4,$5,$6,'SUCCEEDED',$7,jsonb_build_object('schema_version',1,'operation_id',$8::text))`, webapi.ID(), r.Org, r.ActorID, r.Owner, lease.InstanceID, "INSTANCE_"+r.Action, r.Trace, lease.ID); err != nil {
		return err
	}
	if _, err = tx.Exec(ctx, `UPDATE idempotency_records SET expires_at=clock_timestamp()+interval '7 days' WHERE operation_id=$1`, lease.ID); err != nil {
		return err
	}
	if _, err = tx.Exec(ctx, `UPDATE outbox_events SET status='DONE' WHERE operation_id=$1 AND status='PENDING'`, lease.ID); err != nil {
		return err
	}
	return tx.Commit(ctx)
}
